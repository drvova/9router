// Regenerate src/shared/utils/providerIconFiles.js from public/providers/*.png.
// Run after adding/removing provider icon assets:  node scripts/gen-provider-icons.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = readdirSync(join(root, "public/providers"))
  .filter((f) => f.endsWith(".png"))
  .map((f) => f.replace(/\.png$/, ""))
  .sort();

const body =
  `// AUTO-GENERATED by scripts/gen-provider-icons.mjs — do not edit by hand.\n` +
  `// Basenames of every file in public/providers/. Consulted by providerIcon.js so the\n` +
  `// client never requests an icon that does not exist (kills guaranteed-404 bursts).\n` +
  `export const PROVIDER_ICON_FILES = new Set([\n` +
  files.map((f) => `  ${JSON.stringify(f)},`).join("\n") +
  `\n]);\n`;

writeFileSync(join(root, "src/shared/utils/providerIconFiles.js"), body);
console.log(`Wrote ${files.length} icon basenames → src/shared/utils/providerIconFiles.js`);
