// Regenerate src/shared/utils/providerIconFiles.js from public/providers/*.{png,svg,webp}.
// Run after adding/removing provider icon assets:  node scripts/gen-provider-icons.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const EXT_PRIORITY = { png: 0, webp: 1, svg: 2 }; // if a brand ships both, keep the raster

const byBase = new Map();
for (const f of readdirSync(join(root, "public/providers"))) {
  const m = f.match(/^(.+)\.(png|svg|webp)$/i);
  if (!m) continue;
  const [, base, ext] = m;
  const prev = byBase.get(base);
  if (!prev || EXT_PRIORITY[ext.toLowerCase()] < EXT_PRIORITY[prev.split(".").pop().toLowerCase()]) {
    byBase.set(base, f);
  }
}

const entries = [...byBase.entries()].sort(([a], [b]) => a.localeCompare(b));
const body =
  `// AUTO-GENERATED by scripts/gen-provider-icons.mjs — do not edit by hand.\n` +
  `// Maps each provider-icon basename to its actual file in public/providers/.\n` +
  `// Consulted by providerIcon.js so the client only requests icons that exist and\n` +
  `// with the correct extension (svg or png), killing guaranteed-404 bursts.\n` +
  `export const PROVIDER_ICON_FILES = new Map([\n` +
  entries.map(([base, file]) => `  [${JSON.stringify(base)}, ${JSON.stringify(file)}],`).join("\n") +
  `\n]);\n`;

writeFileSync(join(root, "src/shared/utils/providerIconFiles.js"), body);
console.log(`Wrote ${entries.length} icon entries → src/shared/utils/providerIconFiles.js`);
